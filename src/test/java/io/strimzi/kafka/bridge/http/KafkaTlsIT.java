package io.strimzi.kafka.bridge.http;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import io.netty.handler.codec.http.HttpResponseStatus;
import io.strimzi.kafka.bridge.BridgeContentType;
import io.strimzi.kafka.bridge.configuration.KafkaTlsConfiguration;
import io.strimzi.kafka.bridge.extensions.BridgeSuite;
import io.strimzi.kafka.bridge.http.base.AbstractIT;
import io.strimzi.kafka.bridge.httpclient.HttpConsumerService;
import io.strimzi.kafka.bridge.httpclient.HttpProducerService;
import io.strimzi.kafka.bridge.httpclient.HttpResponseUtils;
import io.strimzi.kafka.bridge.objects.BridgeTestContext;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.net.http.HttpResponse;
import java.util.ArrayList;
import java.util.List;

import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.is;

/**
 * Integration tests for the Bridge talking to a Kafka cluster over TLS.
 * The {@link KafkaTlsConfiguration} annotation makes the test setup deploy the Kafka cluster
 * with TLS enabled on the client listener; the cluster requires mutual TLS, so the Bridge
 * is configured with the client truststore and keystore generated by the cluster.
 * The HTTP side of the Bridge is plain HTTP in these tests, everything between the Bridge
 * and Kafka is encrypted and mutually authenticated.
 */
@BridgeSuite
@KafkaTlsConfiguration
public class KafkaTlsIT extends AbstractIT {

    private String name;
    private String groupId;

    private ObjectNode consumer;

    @BeforeEach
    void setUp() {
        name = generateRandomConsumerName();
        groupId = generateRandomConsumerGroupName();

        consumer = MAPPER.createObjectNode()
            .put("name", name)
            .put("format", "json");
    }

    @Test
    void sendAndReceiveMessageOverTls(BridgeTestContext bridgeTestContext) {
        String topic = bridgeTestContext.getTopicName();
        bridgeTestContext.getAdminClientFacade().createTopic(topic, 1);

        String value = "message-value";
        String key = "my-key";

        ObjectNode root = MAPPER.createObjectNode();
        root.putArray("records").add(MAPPER.createObjectNode().put("value", value).put("key", key));

        // produce a record through the Bridge, which forwards it to Kafka over TLS
        HttpProducerService httpProducerService = new HttpProducerService(bridgeTestContext.getHttpService());
        HttpResponse<String> produceResponse = httpProducerService.sendJsonNodeRecordsRequest(topic, root, BridgeContentType.KAFKA_JSON_JSON);
        assertThat(produceResponse.statusCode(), is(HttpResponseStatus.OK.code()));

        JsonNode bridgeResponse = HttpResponseUtils.getResponseAsJsonNode(produceResponse.body());
        ArrayNode offsets = (ArrayNode) bridgeResponse.get("offsets");
        assertThat(offsets.size(), is(1));
        assertThat(offsets.get(0).get("partition").asInt(), is(0));
        assertThat(offsets.get(0).get("offset").asLong(), is(0L));

        // consume the record back through the Bridge, again over TLS on the Kafka side
        HttpConsumerService httpConsumerService = new HttpConsumerService(bridgeTestContext.getHttpService());
        httpConsumerService.createConsumer(groupId, consumer);
        httpConsumerService.subscribeConsumer(groupId, name, topic);

        HttpResponse<String> consumeResponse = httpConsumerService.consumeRecordsRequest(groupId, name);
        assertThat(consumeResponse.statusCode(), is(HttpResponseStatus.OK.code()));

        JsonNode receivedMessage = HttpResponseUtils.getResponseAsJsonNode(consumeResponse.body()).get(0);
        assertThat(receivedMessage.get("topic").asText(), is(topic));
        assertThat(receivedMessage.get("value").asText(), is(value));
        assertThat(receivedMessage.get("key").asText(), is(key));
        assertThat(receivedMessage.get("partition").asInt(), is(0));
        assertThat(receivedMessage.get("offset").asLong(), is(0L));

        httpConsumerService.deleteConsumer(groupId, name);
    }

    @Test
    void sendAndReceiveMultipleMessagesOverTls(BridgeTestContext bridgeTestContext) {
        String topic = bridgeTestContext.getTopicName();
        bridgeTestContext.getAdminClientFacade().createTopic(topic, 1);

        int numMessages = 5;

        ObjectNode root = MAPPER.createObjectNode();
        ArrayNode records = root.putArray("records");
        for (int i = 0; i < numMessages; i++) {
            records.add(MAPPER.createObjectNode().put("value", "message-value-" + i));
        }

        HttpProducerService httpProducerService = new HttpProducerService(bridgeTestContext.getHttpService());
        HttpResponse<String> produceResponse = httpProducerService.sendJsonNodeRecordsRequest(topic, root, BridgeContentType.KAFKA_JSON_JSON);
        assertThat(produceResponse.statusCode(), is(HttpResponseStatus.OK.code()));

        HttpConsumerService httpConsumerService = new HttpConsumerService(bridgeTestContext.getHttpService());
        httpConsumerService.createConsumer(groupId, consumer);
        httpConsumerService.subscribeConsumer(groupId, name, topic);

        // poll until all the records are received, a single poll is not guaranteed to return all of them
        List<JsonNode> receivedMessages = new ArrayList<>();
        int attempts = 0;
        while (receivedMessages.size() < numMessages && attempts < 10) {
            HttpResponse<String> consumeResponse = httpConsumerService.consumeRecordsRequest(groupId, name);
            assertThat(consumeResponse.statusCode(), is(HttpResponseStatus.OK.code()));
            HttpResponseUtils.getResponseAsJsonNode(consumeResponse.body()).forEach(receivedMessages::add);
            attempts++;
        }

        assertThat(receivedMessages.size(), is(numMessages));
        for (int i = 0; i < numMessages; i++) {
            assertThat(receivedMessages.get(i).get("topic").asText(), is(topic));
            assertThat(receivedMessages.get(i).get("value").asText(), is("message-value-" + i));
            assertThat(receivedMessages.get(i).get("offset").asLong(), is((long) i));
        }

        httpConsumerService.deleteConsumer(groupId, name);
    }
}
